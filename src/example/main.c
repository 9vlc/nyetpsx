/*
 * Graph headers contain the nyetpsx graphics abstraction layer.
 * Currently, they are as follows:
 *   graph/gpu.h        - GPU abstractions such as VRAM access and DMA chains
 *   graph/gte.h        - GTE abstractions such as matrix math
 *   graph/geom.h       - Various shape types and their initializers used for drawing
 *   graph/font.h       - Font structure and generic functions (drawers in *draw)
 *   graph/fonts/       - Font files to be used with graph/font.h and following drawers
 *   graph/directdraw.h - Drawing by directly writing to GP0, extremely minimal but slow
 *   graph/dmadraw.h    - Drawing using DMA chains without ordering tables
 *   graph/dmadraw_ot.h - Drawing using DMA chains with ordering tables
 */
#include <graph/gpu.h>
#include <graph/gte.h>
#include <graph/dmadraw_ord.h>
#include <graph/font.h>
/*
 * One of the many fonts we have, generated by scripts/mkfont.py
 * Defines:
 *  font_NAME_sheet               - Spritesheet in 4BPP, 96 ASCII characters
 *  font_NAME_clut                - Color lookup table in 16BPP, 16 max colors
 *  FONT_NAME_SET(SX, SY, CX, CY) - Macro to populate the graph_font_t struct with font data,
 *                                    spritesheet and CLUT separately
 *  FONT_NAME_SET_R(OX, OY)       - Same, just position CLUT below the spritesheet and align
 *                                    the font to top right corner of VRAM, with OX OY being
 *                                    offsets from there.
 */
#include <graph/fonts/sonyfixed_12x24.h>

#include <stdint.h>
#include <stdio.h>

#include "example.h"
#include "background.h"

/*
 * Set a texture stretched as the background
 */
static void
set_tex_bg(
	graph_dma_ord_chain_t *chain,
	graph_texture_info_t *tex
	)
{
	/*
	 * The UVs are the coordinates of each corner of the texture
	 */
	graph_uv_t uv0 = GRAPH_UV(tex->u,              tex->v);
	graph_uv_t uv1 = GRAPH_UV(tex->u + tex->w - 1, tex->v);
	graph_uv_t uv2 = GRAPH_UV(tex->u,              tex->v + tex->h - 1);
	graph_uv_t uv3 = GRAPH_UV(tex->u + tex->w - 1, tex->v + tex->h - 1);

	graph_o_tex_quad(
		chain,
		Z_MAX,
		&GRAPH_QUAD(
			0,            0,
			SCREEN_WIDTH, 0,
			0,            SCREEN_HEIGHT,
			SCREEN_WIDTH, SCREEN_HEIGHT
		),
		COL_CUBE,
		tex,
		&uv0, &uv1,
		&uv2, &uv3,
		false
	);
}

/*
 * This is the entrypoint of the program!
 */
int
main(
	int argc,
	char **argv
	)
{
	/*
	 * Cast argc and argv to void as we're not using them.
	 * If you don't do this, the compiler will get angry!
	 */
	(void)argc;
	(void)argv;

	/*
	 * Print some text over serial I/O if support for that was compiled in.
	 * I believe this is the only way you can get logs from a retail console
	 *   without hooking up Unirom's debugger thing.
	 */
#if STDIO_USE_SIO1 == 1
	sio1_init(115200);
	uprintf("Hello, world!\n");
#endif

	/*
	 * And print text using BIOS' printf!
	 * This is for devkits, emulators and retail consoles with Unirom.
	 */
	sys_printf("Hello from TTY!\n");

	/* Initialize the GPU with the GTE */
	graph_init_gpu(SCREEN_HRES, SCREEN_VRES, SCREEN_WIDTH, SCREEN_HEIGHT);
	graph_init_gte(SCREEN_WIDTH, SCREEN_HEIGHT);

	/*
	 * To use a font, we need to create a graph_font_t struct and populate
	 *   it with font's data using the FONT_NAME_SET(_R) macro.
	 */
	graph_font_t font = FONT_SONYFIXED_12X24_SET_R(0, 0);

	/*
	 * Then, load the font to VRAM and populate struct's font.info.
	 * All this function does is call graph_load_texture(&font->data, &font->info)
	 */
	graph_load_font(&font);

	/*
	 * Create a buffer for the mandelbrot texture, 8BPP with a clut
	 *   below the main view.
	 */
	uint8_t mandel_img[MANDEL_WIDTH * MANDEL_HEIGHT];
	graph_rgb16_t mandel_clut[256];
	graph_texture_data_t mandel_data = {
		.img   = mandel_img,
		.x     = SCREEN_WIDTH,
		.y     = 0,
		.w     = MANDEL_WIDTH,
		.h     = 0,
		.clut  = mandel_clut,
		.cx    = 0,
		.cy    = SCREEN_HEIGHT,
		.depth = GP0_COLOR_8BPP
	};
	graph_texture_info_t mandel_info;
	mandel_generate_clut(mandel_clut);

	/*
	 * Load the background, too, right below the mandelbrot.
	 */
	graph_texture_data_t background_data = {
		.img   = background_img,
		.x     = SCREEN_WIDTH,
		.y     = MANDEL_HEIGHT,
		.w     = BACKGROUND_WIDTH,
		.h     = BACKGROUND_HEIGHT,
		.clut  = background_clut,
		.cx    = 0,
		.cy    = SCREEN_HEIGHT + 1,
		.depth = BACKGROUND_DEPTH
	};
	graph_texture_info_t background_info;
	graph_load_texture(&background_data, &background_info);

	/*
	 * Initialize the cube, this sets the textures of all faces to a pointer
	 *   to mandel_info. Now when we modify it, the texture will modify too.
	 */
	cube_init(&mandel_info);

	/*
	 * By using two separate chains, you can avoid waiting for DMA to finish
	 *   before writing to the chain again and instead swap chains.
	 *
	 * If you're using a lower resolution mode, also consider using two
	 *   separate framebuffers!
	 *
	 * See: https://github.com/spicyjpeg/ps1-bare-metal/blob/main/src/02_doubleBuffer/main.c
	 *      https://github.com/spicyjpeg/ps1-bare-metal/blob/main/src/03_dmaChain/main.c
	 */
	graph_dma_ord_chain_t chains[2];
	bool using_second_frame = false;

	/* Program's drawing cycle */
	while (1) {
		graph_dma_ord_chain_t *chain = &chains[using_second_frame];

		/* Clear ordering table and set chain data poitner */
		graph_clear_ot(chain->ot, GRAPH_DMA_CHAIN_OT_SIZE);
		chain->next = chain->data;

		/*
		 * Append various drawing commands to the chain
		 */

		set_tex_bg(chain, &background_info);

		/*
		 * Check if the texture is not generated yet, render the next
		 *   line if so, together with a progress status.
		 * The graph_load_texture() function awaits for GPU DMA,
		 *   so the double buffer will not play much of a role while
		 *   the textures are being generated.
		 */
		if (mandel_data.h < MANDEL_HEIGHT - 1) {
			char progress[25];

			usnprintf(progress, sizeof(progress), "Mandelbrot: %u / %u",
				mandel_data.h, MANDEL_HEIGHT - 1);

			graph_o_print_str(
				chain,
				0,
				&font,
				&GRAPH_POINT(25, 25),
				progress
			);

			mandel_data.h ++;

			mandel_render_line(
				mandel_img + mandel_data.h * MANDEL_WIDTH,
				MANDEL_WIDTH, MANDEL_HEIGHT,
				mandel_data.h,
				MANDEL_LL_X, MANDEL_LL_Y,
				MANDEL_UR_X, MANDEL_UR_Y,
				MANDEL_MAX_ITER
			);

			graph_load_texture(&mandel_data, &mandel_info);
		}

		cube_render(chain);

		/* Wait for all GPU commands to be finished */
		gpu_await_cmd();

		/* Wait for VSync, then flip the line variable */
		gpu_await_vsync(using_second_frame);

		/* Finally, send the chain to the DMA engine */
		graph_send_chain(&chain->ot[Z_MAX]);

		/* Oh, and flip this variable */
		using_second_frame = !using_second_frame;
	}

	return (0);
}
